const NOTE_OFFSETS = { 1: 0, 2: 2, 3: 4, 4: 5, 5: 7, 6: 9, 7: 11 };
const BASE_DURATION = 500;
const BEAT = 500;

function parseNoteString(str) {
  if (!str || str.length === 0) return null;

  let octaveOffset = 0;
  let idx = 0;

  while (idx < str.length && (str[idx] === '+' || str[idx] === '-')) {
    if (str[idx] === '+') octaveOffset++;
    else octaveOffset--;
    idx++;
  }

  if (idx >= str.length || !'1234567'.includes(str[idx])) return null;

  const baseNote = parseInt(str[idx]);
  idx++;

  let semitoneOffset = 0;
  while (idx < str.length) {
    if (str[idx] === '#') {
      semitoneOffset++;
      idx++;
    } else if (str[idx] === '-' && idx + 1 < str.length && !'1234567'.includes(str[idx + 1])) {
      idx++;
      if (str[idx] === '#') {
        semitoneOffset--;
        idx++;
      } else if (str[idx] === '-') {
        semitoneOffset -= 2;
        idx++;
      } else if ('1234567'.includes(str[idx])) {
        semitoneOffset--;
      } else {
        semitoneOffset--;
      }
    } else {
      break;
    }
  }

  const baseOffset = NOTE_OFFSETS[baseNote];
  const midi = 60 + (octaveOffset * 12) + baseOffset + semitoneOffset;

  return { key: midi };
}

function hasSeparatorDots(str) {
  const match = str.match(/[^.]\.[^.]/);
  return match !== null;
}

function parseSegment(segment) {
  const notes = [];

  if (hasSeparatorDots(segment)) {
    const parts = segment.split('.');
    for (let i = 0; i < parts.length; i++) {
      const part = parts[i];
      const parsed = parseNoteString(part);
      if (parsed) {
        let duration = BASE_DURATION;
        if (part.endsWith('.')) {
          const dotMatch = part.match(/\.+$/);
          if (dotMatch) {
            const dotCount = dotMatch[0].length;
            if (dotCount === 1) duration = 1000;
            else if (dotCount === 2) duration = 1500;
          }
        }
        notes.push({ key: parsed.key, duration });
      }
    }
  } else {
    const dotMatch = segment.match(/\.+$/);
    let dotCount = 0;
    let noteStr = segment;

    if (dotMatch) {
      dotCount = dotMatch[0].length;
      noteStr = segment.slice(0, -dotCount);
    }

    const parsed = parseNoteString(noteStr);
    if (parsed) {
      let duration = BASE_DURATION;
      if (dotCount === 1) duration = 1000;
      else if (dotCount === 2) duration = 1500;
      notes.push({ key: parsed.key, duration });
    }
  }

  return notes;
}

function convertSong(songArray) {
  const result = [];
  let currentTime = 0;

  for (const segment of songArray) {
    const notes = parseSegment(segment);
    for (const note of notes) {
      result.push({
        key: note.key,
        time: currentTime,
        duration: note.duration
      });
    }
    currentTime += BEAT;
  }

  return result;
}

